"""Генерация презентации для защиты: документы/презентация/Презентация_защиты.pptx.

Слайды строятся из результатов проекта (числа) и готовых рисунков
`results/figures/*.png`. Требует необязательный пакет python-pptx
(в основной requirements.txt не входит):

    pip install python-pptx
    python scripts/make_presentation.py
"""

from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIG = os.path.join(ROOT, "results", "figures")
OUT = os.path.join(ROOT, "документы", "презентация", "Презентация_защиты.pptx")

TITLE = ("Исследование помехоустойчивости кодов Хэмминга и свёрточных кодов "
         "при передаче данных по каналу с шумом")


def main() -> None:
    try:
        from pptx import Presentation
        from pptx.util import Inches, Pt
    except ImportError:
        sys.exit("Нужен пакет python-pptx: pip install python-pptx")

    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    blank = prs.slide_layouts[6]
    titled = prs.slide_layouts[1]

    def slide(title: str, bullets: list[str], picture: str | None = None):
        s = prs.slides.add_slide(titled if not picture else blank)
        if picture:
            tf_box = s.shapes.add_textbox(Inches(0.5), Inches(0.25),
                                          Inches(12.3), Inches(0.8))
            tf_box.text_frame.text = title
            tf_box.text_frame.paragraphs[0].font.size = Pt(30)
            body = s.shapes.add_textbox(Inches(0.5), Inches(1.2),
                                        Inches(6.6), Inches(6.0))
            tf = body.text_frame
            tf.word_wrap = True
            for i, b in enumerate(bullets):
                p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
                p.text = "• " + b
                p.font.size = Pt(19)
            pic = os.path.join(FIG, picture)
            if os.path.exists(pic):
                s.shapes.add_picture(pic, Inches(7.3), Inches(1.2),
                                     width=Inches(5.6))
        else:
            s.shapes.title.text = title
            tf = s.placeholders[1].text_frame
            tf.word_wrap = True
            for i, b in enumerate(bullets):
                p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
                p.text = b
                p.font.size = Pt(20)
        return s

    # 1. Титул (ручная раскладка: длинное название не помещается
    # в стандартный placeholder и наслаивается, поэтому — отдельные
    # текстовые блоки с фиксированными размерами шрифта и переносом)
    s = prs.slides.add_slide(blank)
    title_box = s.shapes.add_textbox(Inches(0.7), Inches(0.9),
                                     Inches(11.9), Inches(2.6))
    tf = title_box.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.text = TITLE
    p.font.size = Pt(32)

    sub_box = s.shapes.add_textbox(Inches(0.7), Inches(3.8),
                                   Inches(11.9), Inches(1.2))
    tf = sub_box.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.text = ("Блочный код Хэмминга (7,4) и свёрточный код (7,5)₈ "
              "с декодированием по Витерби в канале BPSK + AWGN")
    p.font.size = Pt(20)

    sign_box = s.shapes.add_textbox(Inches(8.6), Inches(6.05),
                                    Inches(4.2), Inches(1.25))
    tf = sign_box.text_frame
    tf.word_wrap = True
    for i, line in enumerate(("Работу выполнил",
                              "Студент группы 11ОБ-397",
                              "Чурсин А.В.")):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = line
        p.font.size = Pt(16)

    slide("Актуальность и цель", [
        "Реальные каналы вносят ошибки: помехоустойчивое кодирование платит "
        "избыточностью за их исправление.",
        "Инженерный компромисс «выигрыш — скорость — сложность» нельзя оценить "
        "без измерения при одинаковой нормировке энергии на информационный бит.",
        "Цель: количественно оценить, насколько кодирование снижает BER по "
        "сравнению с передачей без кодирования, и сравнить два типа кодов.",
    ])
    slide("Задачи", [
        "Изучить теорию блочных и свёрточных кодов: кодовое расстояние, "
        "скорость кода, энергетический выигрыш.",
        "Реализовать вручную кодер/декодер Хэмминга (7,4) и свёрточный код "
        "R = 1/2, K = 3, (7,5)₈ с декодером Витерби.",
        "Смоделировать канал BPSK + AWGN с жёстким решением и получить "
        "зависимости BER от Eb/N0.",
        "Сравнить схемы, определить энергетический выигрыш при BER = 10⁻⁴, "
        "сделать выводы.",
    ])
    slide("Код Хэмминга (7,4)", [
        "Проверочные биты на позициях 1, 2, 4; информационные — 3, 5, 6, 7.",
        "Синдром напрямую указывает номер ошибочной позиции; исправляется "
        "ровно одна ошибка в блоке (d_min = 3, t = 1).",
        "Скорость R = 4/7; двойная ошибка ошибочно «исправляется» в третью "
        "позицию — декодер выдаёт неверную информацию без признака отказа.",
        "Проверка: исчерпывающий перебор всех 16 слов × 7 позиций одиночных ошибок.",
    ], "hamming_correction.png")
    slide("Свёрточный код и алгоритм Витерби", [
        "Регистр сдвига K = 3, полиномы (7,5)₈, выходы v1 = u⊕a⊕b, v2 = u⊕b.",
        "4 состояния, свободное расстояние d_free = 5 (путь 00→10→01→00, вес 5).",
        "Нулевое завершение решётки: пакет L = 10 000 бит + хвост 2 бита, "
        "R_eff = 0.49990.",
        "Витерби: жёсткие решения, метрика Хэмминга, tie-break — меньшее "
        "предыдущее состояние.",
    ], "state_diagram.png")
    slide("Модель системы связи", [
        "Цепочка: случайные биты → кодер → BPSK → AWGN → жёсткий демодулятор "
        "→ декодер → подсчёт ошибок.",
        "Шум: σ² = 1/(2·R_eff·Eb/N0) — мощность шума пересчитывается с учётом "
        "скорости кода, иначе сравнение некорректно.",
        "BER считается только по информационным битам; хвостовые биты в "
        "подсчёт не входят.",
        "Контрольные варианты: без кодирования, Хэмминг, свёрточный код.",
    ], "channel_scheme.png")
    slide("План эксперимента", [
        "Eb/N0 = 0…10 дБ с шагом 1 дБ; уточняющий прогон по сетке 0.2 дБ "
        "вокруг BER = 10⁻⁴.",
        "Объёмы: 2·10⁶ / 2·10⁶ / 10⁶ информационных бит на точку; расширенный "
        "прогон — в 10 раз больше.",
        "Фиксированные seed (20261024, 20261026, bootstrap 777001), объёмы "
        "зафиксированы до запуска и не подбирались по результатам.",
        "119 автоматических тестов: безошибочный канал, одиночные ошибки, "
        "сверка Витерби с полным перебором.",
    ])
    slide("Зависимости BER от Eb/N0", [
        "Все три кривые на одном графике, логарифмическая шкала BER.",
        "Некодированная кривая согласуется с теорией BPSK в пределах "
        "статистической погрешности.",
        "При Eb/N0 ≲ 4 дБ кодирование проигрывает: избыточность снижает "
        "энергию на информационный бит сильнее, чем даёт исправление ошибок.",
        "Далее выигрыш растёт с уменьшением BER.",
    ], "ber_comparison.png")
    slide("Энергетический выигрыш при BER = 10⁻⁴", [
        "Свёрточный код (7,5)₈ + Витерби: +1.4 дБ (сетка 0.2 дБ: "
        "+1.39 [+1.34; +1.43] дБ).",
        "Код Хэмминга (7,4): +0.3 дБ (сетка 0.2 дБ: +0.32 [+0.29; +0.34] дБ).",
        "Интервалы — кластерный bootstrap, 10 000 реплик; разница способов "
        "интерполяции (0.10 / 0.19 дБ) учитывается отдельно и с bootstrap "
        "не складывается.",
    ], "ber_zoom.png")
    slide("Почему свёрточный код выигрывает больше", [
        "Память кодера и решётчатое декодирование используют структуру всей "
        "последовательности, а не одного блока из 7 бит.",
        "d_free = 5 против d_min = 3 при сопоставимой цене по скорости "
        "(≈1/2 против 4/7).",
        "Хэмминг исправляет только одиночные ошибки и бессилен против двойных; "
        "его выигрыш на уровне 10⁻⁴ — десятые доли дБ.",
    ])
    slide("Честность статистики и ограничения", [
        "Ориентир «≥100 ошибок на точку» при 8–10 дБ недостижим в разумное "
        "время: в расширенном прогоне у свёрточного кода при 9–10 дБ — 7 и 1 "
        "ошибка. Вместо фиктивной точности приведены границы 95 %.",
        "Точки без ошибок даны верхней границей, а не BER = 0.",
        "Моделировались только жёсткие решения и идеальный AWGN без "
        "замираний; выводы — для заданных параметров кодов.",
    ])
    slide("Выводы", [
        "Обе схемы реализованы вручную и проверены независимыми тестами; "
        "модель канала нормирована на информационный бит.",
        "При BER = 10⁻⁴: свёрточный код с Витерби даёт +1.4 дБ, код Хэмминга "
        "(7,4) — +0.3 дБ относительно передачи без кодирования.",
        "При Eb/N0 ≲ 4 дБ кодирование невыгодно; выигрыш появляется и растёт "
        "с ростом Eb/N0.",
        "Проект полностью воспроизводим: seed, версии, параметры и все "
        "исходные CSV сохранены в репозитории.",
    ])
    slide("Вопросы преподавателя: реализация (вопрос — ответ)", [
        "В: Почему порядок битов p1 p2 d1 p4 d2 d3 d4? — О: синдром напрямую "
        "равен номеру ошибочной позиции, таблица поиска не нужна.",
        "В: Что при двойной ошибке Хэмминга? — О: синдром ненулевой, но ошибка "
        "ошибочно «исправляется» в третью позицию, без признака отказа (d_min = 3).",
        "В: Откуда d_free = 5 у свёрточного кода? — О: кратчайший путь "
        "00→10→01→00 по диаграмме состояний, выход 11|10|11 веса 5.",
        "В: Почему только жёсткие решения? — О: заданы постановкой; мягкие "
        "не моделировались, и их преимущество в цифрах не утверждается.",
    ])
    slide("Вопросы преподавателя: эксперимент и статистика (вопрос — ответ)", [
        "В: Зачем σ² делить на R_eff? — О: Eb — энергия на информационный бит; "
        "иначе кодирование получило бы «бесплатную» энергию и завышенный выигрыш.",
        "В: Почему не набрано 100 ошибок при 9–10 дБ? — О: при BER ~10⁻⁷ нужно "
        "~10⁹ бит; вместо фиктивной точности приведены границы 95 %.",
        "В: Почему интервалы по блокам и пакетам, а не по битам? — О: ошибки "
        "внутри блока зависимы; независимая единица — блок (4 бита) или пакет.",
        "В: Результат воспроизводим? — О: фиксированные seed и независимые "
        "потоки SeedSequence; повторный прогон даёт те же счётчики бит-в-бит.",
    ])
    slide("Вопросы преподавателя: результаты (вопрос — ответ)", [
        "В: Почему Хэмминг проигрывает при малых Eb/N0? — О: избыточность 7/4 "
        "стоит ≈2.43 дБ и не окупается, пока ошибок в блоке много; выигрыш с ~4 дБ.",
        "В: Почему свёрточный код лучше? — О: память кодера и решение по всей "
        "решётке, d_free = 5; цена — скорость ≈1/2 и медленное декодирование.",
        "В: Насколько точны +1.4 и +0.3 дБ? — О: сетка 0.2 дБ: +1.39 [+1.34; +1.43] "
        "и +0.32 [+0.29; +0.34] дБ, bootstrap 10 000 реплик.",
        "Полный список вопросов и ответов: документы/Вопросы_к_защите.md в репозитории проекта.",
    ])
    slide("Спасибо за внимание!", [
        "Вопросы?",
        "Код, данные, графики и notebook: репозиторий проекта "
        "(notebooks/01_research.ipynb — главный документ, 19 разделов).",
        "Все вопросы и ответы к защите: документы/Вопросы_к_защите.md.",
    ])

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    prs.save(OUT)
    print(f"записано: {OUT} ({len(prs.slides.__iter__.__self__._sldIdLst)} слайдов)")


if __name__ == "__main__":
    main()
